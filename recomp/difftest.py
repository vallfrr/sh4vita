"""Differential test of the x86 -> C translator: each instruction form present in the game is
executed in Unicorn (reference) and via the C generated by x86rec.Func.insn, on random states;
registers, defined flags and touched memory must match.

Usage : python recomp/difftest.py [cas_par_forme=24] [--keep]
"""
import collections, os, pathlib, random, struct, subprocess, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import x86rec
from x86rec import Recompiler, Func, X
import unicorn
from unicorn import x86_const as U

ROOT = pathlib.Path(__file__).resolve().parent.parent
SDL = "J:/tools/sdl2/SDL2-2.32.10/x86_64-w64-mingw32"
OUT = ROOT / "build" / "difftest"
SCRATCH, SCRATCH_SZ = 0x00100000, 0x00100000
REGS = ["eax", "ecx", "edx", "ebx", "esp", "ebp", "esi", "edi"]
UREG = [U.UC_X86_REG_EAX, U.UC_X86_REG_ECX, U.UC_X86_REG_EDX, U.UC_X86_REG_EBX, U.UC_X86_REG_ESP,
        U.UC_X86_REG_EBP, U.UC_X86_REG_ESI, U.UC_X86_REG_EDI]
CF, PF, ZF, SF, OF = 1, 4, 0x40, 0x80, 0x800
ALL = CF | PF | ZF | SF | OF
SKIP = {"call", "ret", "jmp", "jecxz", "int3", "hlt", "ud2", "nop", "wait", "cpuid", "pushfd", "popfd", "leave",
        "pushal", "popal", "std", "cld"}


def defined_flags(mn, ins):
    base = mn.split()[-1]
    if base in ("add", "adc", "sub", "sbb", "cmp", "neg", "cmpsb", "cmpsd", "cmpsw", "scasb", "scasd"):
        return ALL
    if base in ("inc", "dec"):
        return ALL
    if base in ("and", "or", "xor", "test"):
        return ALL
    if base in ("shl", "sal", "shr", "sar", "shld", "shrd"):
        cnt = ins.operands[-1]
        if cnt.type == X.X86_OP_IMM and (cnt.imm & 31) == 1:
            return ALL
        return CF | PF | ZF | SF  # OF undefined if count != 1
    if base == "rcr":
        return CF | OF
    if base in ("imul", "mul"):
        return CF | OF
    if base in ("div", "idiv"):
        return 0
    if base in ("bt", "bts"):
        return CF
    if base == "sahf":
        return CF | PF | ZF | SF
    return ALL  # instructions without effect on flags: everything must stay unchanged


def shape(ins):
    ops = []
    for op in ins.operands:
        if op.type == X.X86_OP_REG:
            ops.append(f"r{op.size}" + ("h" if ins.reg_name(op.reg).endswith("h") else ""))
        elif op.type == X.X86_OP_IMM:
            ops.append(f"i{op.size}")
        else:
            m = op.mem
            ops.append(f"m{op.size}{'b' if m.base else ''}{'x' if m.index else ''}{'s' if m.segment else ''}")
    return (ins.mnemonic, tuple(ops), ins.prefix[2])


def interesting(rng):
    return rng.choice([0, 1, 2, 0x7f, 0x80, 0xff, 0x100, 0x7fff, 0x8000, 0xffff, 0x7fffffff, 0x80000000,
                       0xfffffffe, 0xffffffff, rng.getrandbits(32), rng.getrandbits(32), rng.getrandbits(8),
                       rng.getrandbits(16)])


def make_case(ins, rng):
    """Initial state: registers, flags, memory blocks (address, bytes)."""
    regs = [interesting(rng) for _ in range(8)]
    regs[4] = SCRATCH + 0x80000 + rng.randrange(0, 0x100) * 4  # esp in the scratch area
    if ins.mnemonic.split()[-1] in ("div", "idiv"):  # avoid #DE: non-zero divisor, small quotient
        regs[2] = rng.getrandbits(8)
    mem = []
    for op in ins.operands:
        if op.type != X.X86_OP_MEM:
            continue
        m = op.mem
        if m.segment:
            return None
        target = SCRATCH + rng.randrange(0x1000, 0x7f000)
        base = ins.reg_name(m.base) if m.base else None
        idx = ins.reg_name(m.index) if m.index else None
        if base and base not in REGS or idx and idx not in REGS:
            return None
        if idx and idx != base:
            if idx == "esp":
                return None
            iv = rng.randrange(0, 64)
            regs[REGS.index(idx)] = iv
        else:
            iv = 0
        if base:
            if base == "esp":
                target = regs[4] + m.disp + (iv * m.scale if idx else 0)
            else:
                bv = (target - m.disp - iv * m.scale) & 0xffffffff
                if idx == base:
                    return None
                regs[REGS.index(base)] = bv
        elif not idx:
            target = m.disp & 0xffffffff
            if not (0x400000 <= target < 0x13e3000):
                return None
        else:
            target = (m.disp + iv * m.scale) & 0xffffffff
            if not (0x400000 <= target < 0x13e3000):
                return None
        lo = (target - 64) & ~3
        mem.append((lo, bytes(rng.getrandbits(8) for _ in range(160))))
    lo = (regs[4] - 64) & ~3
    mem.append((lo, bytes(rng.getrandbits(8) for _ in range(160))))
    if ins.mnemonic.split()[0] in ("rep", "repe", "repne"):
        regs[1] = rng.randrange(0, 6)  # ecx petit
        for r in ("esi", "edi"):
            regs[REGS.index(r)] = SCRATCH + rng.randrange(0x1000, 0x7f000)
            mem.append(((regs[REGS.index(r)] - 64) & ~3, bytes(rng.getrandbits(8) for _ in range(160))))
    elif ins.mnemonic.split()[-1] in ("movsb", "movsd", "movsw", "stosb", "stosd", "stosw", "cmpsb", "cmpsd",
                                      "scasb", "scasd"):
        for r in ("esi", "edi"):
            regs[REGS.index(r)] = SCRATCH + rng.randrange(0x1000, 0x7f000)
            mem.append(((regs[REGS.index(r)] - 64) & ~3, bytes(rng.getrandbits(8) for _ in range(160))))
    flags = rng.getrandbits(32) & ALL | 2
    return regs, flags, mem


def run_unicorn(ins, case):
    regs, flags, mem = case
    uc = unicorn.Uc(unicorn.UC_ARCH_X86, unicorn.UC_MODE_32)
    pages = {ins.address & ~0xfff, (ins.address + 15) & ~0xfff}
    for a, b in mem:
        for p in range(a & ~0xfff, (a + len(b) + 0xfff) & ~0xfff, 0x1000):
            pages.add(p)
    for p in sorted(pages):
        try:
            uc.mem_map(p, 0x1000)
        except unicorn.UcError:
            pass
    uc.mem_write(ins.address, bytes(ins.bytes))
    for a, b in mem:
        uc.mem_write(a, b)
    for r, v in zip(UREG, regs):
        uc.reg_write(r, v)
    uc.reg_write(U.UC_X86_REG_EFLAGS, flags)
    try:
        uc.emu_start(ins.address, ins.address + ins.size, count=1)
    except unicorn.UcError:
        return None
    if uc.reg_read(U.UC_X86_REG_EIP) != ins.address + ins.size and ins.mnemonic.split()[0] not in ("rep", "repe", "repne"):
        return None
    out_regs = [uc.reg_read(r) & 0xffffffff for r in UREG]
    out_mem = [bytes(uc.mem_read(a, len(b))) for a, b in mem]
    return out_regs, uc.reg_read(U.UC_X86_REG_EFLAGS), out_mem


def emit_test(rec, ins, n):
    f = Func.__new__(Func)
    f.rec, f.entry, f.insns, f.addrs = rec, ins.address, [ins], {ins.address}
    f.labels, f.switches, f.out, f.flagsrc = set(), {}, [], None
    try:
        f.insn(ins)
    except Exception:
        return None
    body = "\n".join(f.out)
    if "goto" in body or "return" in body or "rt_call" in body or "rt_unimpl" in body:
        return None
    return (f"static void T{n}(CPU *c, uint32_t *fl) {{\n  uint8_t *const mb = g_mem;\n"
            f"  uint32_t eax=c->eax,ecx=c->ecx,edx=c->edx,ebx=c->ebx,esp=c->esp,ebp=c->ebp,esi=c->esi,edi=c->edi;\n"
            f"  uint32_t cf=fl[0],pf=fl[1],zf=fl[2],sf=fl[3],of=fl[4],fa=0,fb=0,fr=0;\n"
            f"  (void)fa;(void)fb;(void)fr;\n{body}\n"
            f"  c->eax=eax;c->ecx=ecx;c->edx=edx;c->ebx=ebx;c->esp=esp;c->ebp=ebp;c->esi=esi;c->edi=edi;\n"
            f"  fl[0]=cf;fl[1]=pf;fl[2]=zf;fl[3]=sf;fl[4]=of;\n}}\n")


HARNESS_MAIN = r"""
#include <stdio.h>
#include <stdlib.h>
extern uint32_t g_mem_size;
const struct { uint32_t a; gfn f; } x86_functab[1]; const unsigned x86_functab_n = 0;
const struct { uint32_t slot; gfn f; const char *name; } x86_iat[1]; const unsigned x86_iat_n = 0;
const uint32_t x86_entry = 0;
void gheap_init(uint32_t b, uint32_t s) { (void)b; (void)s; }
uint32_t gheap_alloc(uint32_t s) { (void)s; return 0; } uint32_t gheap_calloc(uint32_t s) { (void)s; return 0; }
uint32_t gheap_alloc_aligned(uint32_t s, uint32_t a) { (void)s; (void)a; return 0; }
void rt_platform_fatal(const char *m) { fprintf(stderr, "%s\n", m); }
int main(int argc, char **argv) {
  g_mem_size = 0x14000000u;
  g_mem = calloc(1, g_mem_size);
  FILE *in = fopen(argv[1], "rb"), *out = fopen(argv[2], "wb");
  uint32_t hdr[15];
  while (fread(hdr, 4, 15, in) == 15) {
    uint32_t id = hdr[0], nb = hdr[14];
    CPU c = {0}; c.fcw = 0x27f;
    memcpy(&c.eax, hdr + 1, 32);
    uint32_t fl[5] = {hdr[9], hdr[10], hdr[11], hdr[12], hdr[13]};
    uint32_t addr[16], len[16];
    for (uint32_t i = 0; i < nb; i++) { fread(&addr[i], 4, 1, in); fread(&len[i], 4, 1, in); fread(g_mem + addr[i], 1, len[i], in); }
    TESTS[id](&c, fl);
    fwrite(&c.eax, 4, 8, out); fwrite(fl, 4, 5, out);
    for (uint32_t i = 0; i < nb; i++) fwrite(g_mem + addr[i], 1, len[i], out);
  }
  fclose(out);
  return 0;
}
"""


def main():
    per = int(sys.argv[1]) if len(sys.argv) > 1 and sys.argv[1].isdigit() else 24
    rng = random.Random(1234)
    rec = Recompiler()
    shapes = collections.defaultdict(list)
    for entry, addrs in rec.funcs.items():
        for a in addrs:
            ins = rec.decode(a)
            if not ins:
                continue
            base = ins.mnemonic.split()[-1]
            if base in SKIP or base.startswith("j") or ins.opcode[0] in range(0xD8, 0xE0):
                continue
            k = shape(ins)
            if len(shapes[k]) < 3:
                shapes[k].append(ins)
    tests, cases, refs = [], [], []
    for k, insns in shapes.items():
        for ins in insns:
            code = emit_test(rec, ins, len(tests))
            if not code:
                continue
            tid = len(tests)
            tests.append((code, ins))
            for _ in range(per):
                cs = make_case(ins, rng)
                if not cs:
                    continue
                ref = run_unicorn(ins, cs)
                if ref:
                    cases.append((tid, cs))
                    refs.append(ref)
    OUT.mkdir(parents=True, exist_ok=True)
    src = ['#include "x86rt.h"'] + [c for c, _ in tests]
    src.append("static void (*const TESTS[])(CPU *, uint32_t *) = {" + ",".join(f"T{i}" for i in range(len(tests))) + "};")
    src.append(HARNESS_MAIN)
    (OUT / "difftest.c").write_text("\n".join(src), encoding="utf-8")
    with open(OUT / "cases.bin", "wb") as f:
        for tid, (regs, flags, mem) in cases:
            fl = [(flags >> 0) & 1, (flags >> 2) & 1, (flags >> 6) & 1, (flags >> 7) & 1, (flags >> 11) & 1]
            f.write(struct.pack("<15I", tid, *regs, *fl, len(mem)))
            for a, b in mem:
                f.write(struct.pack("<II", a, len(b)) + b)
    env = dict(os.environ, PATH=f"J:/tools/mingw64/bin;{SDL}/bin;" + os.environ["PATH"])
    exe = OUT / "difftest.exe"
    r = subprocess.run(["J:/tools/mingw64/bin/gcc.exe", "-std=gnu11", "-O1", "-w", f"-I{ROOT / 'port/src/rt'}", f"-I{SDL}/include", f"-I{SDL}/include/SDL2",
                        str(OUT / "difftest.c"), str(ROOT / "port/src/rt/x86rt.c"), "-o", str(exe), f"-L{SDL}/lib", "-lSDL2", "-lm"], env=env, capture_output=True, text=True)
    if r.returncode:
        print(r.stderr[:4000])
        return
    subprocess.run([str(exe), str(OUT / "cases.bin"), str(OUT / "out.bin")], check=True, env=env)
    data = (OUT / "out.bin").read_bytes()
    pos, fails = 0, collections.Counter()
    examples = {}
    for (tid, (regs, flags, mem)), (ur, uf, um) in zip(cases, refs):
        cr = struct.unpack_from("<8I", data, pos); pos += 32
        cfl = struct.unpack_from("<5I", data, pos); pos += 20
        cm = []
        for a, b in mem:
            cm.append(data[pos:pos + len(b)]); pos += len(b)
        ins = tests[tid][1]
        mask = defined_flags(ins.mnemonic, ins)
        mine = (cfl[0] & 1) | (cfl[1] & 1) << 2 | (cfl[2] & 1) << 6 | (cfl[3] & 1) << 7 | (cfl[4] & 1) << 11
        why = []
        if list(cr) != ur:
            why.append("regs " + " ".join(f"{REGS[i]}:{cr[i]:08x}!={ur[i]:08x}" for i in range(8) if cr[i] != ur[i]))
        if (mine ^ uf) & mask:
            why.append(f"flags {mine & mask:#x} != {uf & mask:#x} (diff {(mine ^ uf) & mask:#x})")
        if cm != um:
            why.append("memory")
        if why:
            key = f"{ins.mnemonic} {ins.op_str}"
            fails[key] += 1
            examples.setdefault(key, (ins, regs, flags, why))
    total = len(cases)
    print(f"{len(shapes)} shapes, {len(tests)} tests, {total} cases, {sum(fails.values())} failures")
    for k, n in fails.most_common(40):
        ins, regs, flags, why = examples[k]
        print(f"  {n:4}  {k:40} @0x{ins.address:x}  {'; '.join(why)[:150]}")


if __name__ == "__main__":
    main()
